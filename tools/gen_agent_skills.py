#!/usr/bin/env python3
"""Generate plugins/89-agent-skills.js from addyosmani/agent-skills (MIT, (c) 2025 Addy Osmani).
usage: python3 tools/gen_agent_skills.py [<agent-skills clone dir>]"""
import sys, os, json, gzip, base64, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/-home-claude/1b577ff5-d668-57ed-ae55-41bcfa1bc43b/scratchpad/ext/agent-skills'
sk = os.path.join(SRC, 'skills')
bodies, index = {}, []
for n in sorted(os.listdir(sk)):
    p = os.path.join(sk, n, 'SKILL.md')
    if not os.path.isfile(p): continue
    t = open(p, encoding='utf-8').read(); bodies[n] = t
    m = re.search(r'^description:\s*(.+)$', t, re.M); d = (m.group(1).strip().strip('"\'') if m else n)
    first = re.split(r'(?<=\.)\s', d, maxsplit=1)[0]
    index.append({'name': n, 'desc': first[:110], 'full': d[:400]})
b64 = base64.b64encode(gzip.compress(json.dumps(bodies, ensure_ascii=False).encode(), 9, mtime=0)).decode()

TEMPLATE = r'''/* plugins/89-agent-skills.js — GENERATED by tools/gen_agent_skills.py; do not edit by hand.
 * Bundles addyosmani/agent-skills — https://github.com/addyosmani/agent-skills
 * MIT License, Copyright (c) 2025 Addy Osmani. Permission is hereby granted, free of charge, to any person obtaining a copy
 * of this software, to deal in the Software without restriction, subject to including this notice. THE SOFTWARE IS PROVIDED "AS IS".
 */
DS.plugin({ name: 'agent-skills', title: 'Agent skills (Addy Osmani)', version: '1.0.0', description: '__N__ engineering skills (spec → plan → build → test → review → ship) from addyosmani/agent-skills (MIT), loadable via use_skill.', apply(ctx) {
  const SRC = 'https://github.com/addyosmani/agent-skills', RAW = 'https://raw.githubusercontent.com/addyosmani/agent-skills/main/skills/';
  const INDEX = __INDEX__;
  const GZ = '__B64__';
  const esc = DS.util.esc, bodies = {}, regs = new Map();
  const cfg = () => Object.assign({ enabled: true, meta: true }, ctx.data.get('cfg') || {});
  let mode = 'pending', all = null;
  async function inflate() {
    if (typeof DecompressionStream !== 'function' || typeof Blob !== 'function' || typeof Response !== 'function') throw new Error('no DecompressionStream');
    const bin = atob(GZ), u8 = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);
    const txt = await new Response(new Blob([u8]).stream().pipeThrough(new DecompressionStream('gzip'))).text();
    return JSON.parse(txt);
  }
  const ready = (async () => {
    try { all = await inflate(); Object.assign(bodies, all); mode = 'bundled'; }
    catch (e) { mode = 'remote'; DS.kernel.log('info', 'agent-skills', 'bundled data unavailable (' + e.message + '); bodies load from raw.githubusercontent.com'); }
    return mode;
  })();
  async function load(name) {
    if (bodies[name]) return bodies[name]; await ready; if (bodies[name]) return bodies[name];
    const r = await fetch(RAW + encodeURIComponent(name) + '/SKILL.md'); if (!r.ok) throw new Error('HTTP ' + r.status + ' fetching ' + name);
    return (bodies[name] = await r.text());
  }
  function register() {
    if (regs.size) return;
    for (const s of INDEX) {
      const spec = { id: 'as-' + s.name, title: s.name.replace(/-/g, ' '), description: s.desc };
      Object.defineProperty(spec, 'instructions', { enumerable: true, configurable: true, get: () => bodies[s.name] || ('(Not loaded yet — fetching ' + RAW + s.name + '/SKILL.md; call use_skill again.)') });
      regs.set(s.name, ctx.skill(spec));
    }
  }
  function unregister() { regs.forEach(off => { try { off && off(); } catch (_) {} }); regs.clear(); }
  if (cfg().enabled) register();
  /* use_skill reads `instructions` synchronously, so make sure the body is present before the tool runs (covers the fetch fallback). */
  ctx.hook('beforeTool', async p => { if (p && p.name === 'use_skill' && p.args && /^as-/.test(String(p.args.id || ''))) { try { await load(String(p.args.id).slice(3)); } catch (_) {} } });
  ctx.prompt({ id: 'agent-skills-meta', build: () => (cfg().enabled && cfg().meta) ? 'Agent skills (Addy Osmani, MIT): for engineering work follow spec → plan → build → test → review → ship. Pick the matching as-* skill from the list and load it with use_skill before starting (e.g. as-spec-driven-development for a new feature, as-test-driven-development while building, as-code-review-and-quality before shipping). See as-using-agent-skills for routing.' : '' });
  ctx.provide('forge.agentSkills', { ready, load, list: () => INDEX.map(s => s.name), mode: () => mode, source: SRC });

  async function view(name) {
    const box = DS.util.el('div', { class: 'as-view' }); box.style.cssText = 'max-width:100%;overflow-wrap:anywhere';
    box.innerHTML = '<div style="font-size:12px;color:var(--muted);margin-bottom:8px">From <a href="' + esc(SRC) + '" target="_blank" rel="noopener">addyosmani/agent-skills</a> · MIT © 2025 Addy Osmani</div><pre style="white-space:pre-wrap;word-break:break-word;max-width:100%;font-size:12px">Loading…</pre>';
    const sh = DS.ui.sheet({ title: name, node: box }); const pre = box.querySelector('pre');
    try { pre.textContent = await load(name); } catch (e) { pre.textContent = 'Could not load: ' + e.message; }
    return sh;
  }
  ctx.settings({ id: 'agent-skills', title: 'Agent skills (Addy Osmani)', render(el) {
    const c = cfg(); el.style.maxWidth = '100%';
    el.innerHTML = '<div style="font-size:12.5px;color:var(--text-2);margin:4px 0 8px;overflow-wrap:anywhere">' + INDEX.length + ' skills from <a href="' + esc(SRC) + '" target="_blank" rel="noopener">' + esc(SRC.replace('https://', '')) + '</a> — MIT License, © 2025 Addy Osmani. Data: <span class="as-mode">' + esc(mode) + '</span>.</div>'
      + '<label style="display:flex;gap:8px;align-items:center;min-height:40px"><input type="checkbox" class="as-en"' + (c.enabled ? ' checked' : '') + '> Enable the pack (registers as-* skills for use_skill)</label>'
      + '<label style="display:flex;gap:8px;align-items:center;min-height:40px"><input type="checkbox" class="as-meta"' + (c.meta ? ' checked' : '') + '> Routing note in system prompt (using-agent-skills)</label>'
      + '<div class="as-list" style="display:flex;flex-direction:column;gap:4px;margin-top:6px"></div>';
    const save = p => { ctx.data.set('cfg', Object.assign(cfg(), p)); };
    el.querySelector('.as-en').onchange = e => { save({ enabled: e.target.checked }); e.target.checked ? register() : unregister(); };
    el.querySelector('.as-meta').onchange = e => save({ meta: e.target.checked });
    const list = el.querySelector('.as-list');
    for (const s of INDEX) {
      const row = DS.util.el('div'); row.style.cssText = 'display:flex;gap:8px;align-items:center;min-width:0';
      row.innerHTML = '<div style="flex:1;min-width:0"><div style="font-weight:600;font-size:13px;overflow-wrap:anywhere">' + esc(s.name) + '</div><div style="font-size:11.5px;color:var(--muted);overflow-wrap:anywhere">' + esc(s.desc) + '</div></div><button class="btn as-v" style="min-height:40px;min-width:56px;flex:none" data-n="' + esc(s.name) + '">view</button>';
      row.querySelector('.as-v').onclick = () => view(s.name); list.appendChild(row);
    }
    ready.then(() => { const m = el.querySelector('.as-mode'); if (m) m.textContent = mode; });
  } });
  ctx.command({ name: 'skills-addy', args: '[name]', desc: "Addy Osmani's agent skills: list, or view one", async run(a, c) {
    const n = String(a || '').trim().replace(/^as-/, '');
    if (n && INDEX.some(s => s.name === n)) { view(n); return c.reply('Opened **' + esc(n) + '** (load it in a run with `use_skill as-' + esc(n) + '`).'); }
    c.reply("**Addy Osmani's agent skills** (MIT, [source](" + SRC + ")) — " + (cfg().enabled ? 'enabled' : 'disabled in Settings') + ':\n' + INDEX.map(s => '- `as-' + esc(s.name) + '` — ' + esc(s.desc)).join('\n'));
  } });
  ctx.intent({ id: 'agent-skills', order: 48, match: t => /\b(addy|agent[- ]skills)\b/i.test(t) || /spec\s*(→|->)\s*plan/i.test(t),
    script: () => [
      { say: "Loading Addy Osmani's spec-driven-development skill (MIT) — the first step of spec → plan → build → test → review → ship.\n\n", tool: { name: 'use_skill', args: { id: 'as-spec-driven-development' } } },
      { final: rs => 'Loaded **as-spec-driven-development**. ' + INDEX.length + ' skills are available as `as-*` (see `/skills-addy`).\n\n> ' + String((rs[0] && rs[0].instructions) || '').split('\n').filter(l => l.trim() && !/^(---|name:|description:)/.test(l)).slice(0, 3).join('\n> ') }] });
  ctx.suggest({ id: 'agent-skills', emoji: '🛠️', title: "Use Addy's agent skills", sub: 'spec → plan → build → test → review → ship', prompt: "Use Addy's agent skills: spec → plan → build → test → review → ship" });
} });
'''
out = (TEMPLATE.replace('__N__', str(len(index)))
       .replace('__INDEX__', json.dumps(index, ensure_ascii=False))
       .replace('__B64__', b64))
dst = os.path.join(ROOT, 'plugins', '89-agent-skills.js')
open(dst, 'w', encoding='utf-8').write(out)
print('wrote', dst, len(index), 'skills,', len(b64), 'b64 bytes')
