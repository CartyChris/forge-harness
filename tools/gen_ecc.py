def read(p):
    with open(p, encoding='utf-8', errors='replace') as f: return f.read()

def front(md):
    m = re.match(r'^---\s*\n(.*?)\n---\s*\n?', md, re.S)
    out = {}
    if not m: return out
    lines = m.group(1).split('\n'); i = 0
    while i < len(lines):
        mm = re.match(r'^([A-Za-z_-]+):\s*(.*)$', lines[i])
        if mm:
            k, v = mm.group(1), mm.group(2).strip()
            if v in ('|', '>', '|-', '>-', ''):  # block scalar / list
                buf = []; i += 1
                while i < len(lines) and (lines[i].startswith(' ') or lines[i].startswith('\t') or not lines[i].strip()):
                    buf.append(lines[i].strip().lstrip('- ').strip()); i += 1
                out[k] = ' '.join(x for x in buf if x) if k != 'tools' else ', '.join(x for x in buf if x)
                continue
            out[k] = v.strip('"\'')
        i += 1
    return out

def short(s, n=120):
    s = re.sub(r'\s+', ' ', s or '').strip()
    return s if len(s) <= n else s[:n - 1].rstrip() + '…'

def main():
    agents_dir = os.path.join(SRC, 'agents'); skills_dir = os.path.join(SRC, 'skills')
    bundle, idx = {}, {'agents': [], 'skills': [], 'rules': [], 'core': [], 'tools': {}}
    for p in sorted(glob.glob(os.path.join(agents_dir, '*.md'))):
        n = os.path.basename(p)[:-3]; md = read(p); fm = front(md)
        idx['agents'].append([n, short(fm.get('description', ''))])
        if n in CORE:
            bundle['agents/' + n + '.md'] = md; idx['core'].append(n)
            idx['tools'][n] = [t.strip().strip('[]"\'') for t in re.split(r'[,\s]+', fm.get('tools', '').strip('[]')) if t.strip().strip('[]"\'')]
    for d in sorted(os.listdir(skills_dir)):
        p = os.path.join(skills_dir, d, 'SKILL.md')
        if not os.path.isfile(p): continue
        md = read(p); fm = front(md)
        idx['skills'].append([d, short(fm.get('description', ''))])
        if d in SKILLS: bundle['skills/' + d + '/SKILL.md'] = md
    for p in sorted(glob.glob(os.path.join(SRC, 'rules', 'common', '*.md'))):
        n = os.path.basename(p)[:-3]; bundle['rules/common/' + n + '.md'] = read(p); idx['rules'].append(n)
    raw = json.dumps(bundle, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    gz = base64.b64encode(gzip.compress(raw, 9, mtime=0)).decode('ascii')
    js = TEMPLATE.replace('__INDEX__', json.dumps(idx, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')).replace('__GZ__', gz)
    with open(OUT, 'w', encoding='utf-8') as f: f.write(js)
    print('wrote %s: %d bytes (bundle raw %d, gz+b64 %d) · %d agents, %d skills, %d rules, %d core, %d bundled skills' % (
        os.path.normpath(OUT), len(js.encode('utf-8')), len(raw), len(gz), len(idx['agents']), len(idx['skills']), len(idx['rules']), len(idx['core']),
        sum(1 for k in bundle if k.startswith('skills/'))))

